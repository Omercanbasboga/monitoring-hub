// Turns Natural Earth 1:50m land (public domain, via the world-atlas package)
// into one SVG path for the Mediterranean, so the dashboard draws its map
// without a tile server. Run with `npm run map` after changing the extent.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoMercator, geoPath } from "d3-geo";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-50m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

const WIDTH = 1000;
const HEIGHT = 450;
const EXTENT = {
  type: "LineString",
  coordinates: [
    [-3, 32.6],
    [36.6, 45.9],
  ],
};

const projection = geoMercator().fitExtent(
  [
    [0, 0],
    [WIDTH, HEIGHT],
  ],
  EXTENT
);
// clip to the frame so the path stays small
const clip = projection.clipExtent([
  [-20, -20],
  [WIDTH + 20, HEIGHT + 20],
]);
const d = geoPath(clip).digits(1)(land);

const out = `// Generated by scripts/build-map.mjs from Natural Earth 1:50m land. Do not edit.
export const WIDTH = ${WIDTH};
export const HEIGHT = ${HEIGHT};
export const SCALE = ${projection.scale()};
export const TRANSLATE = ${JSON.stringify(projection.translate())};
export const LAND = ${JSON.stringify(d)};
`;
writeFileSync(new URL("../src/map/mediterranean.js", import.meta.url), out);
console.log(`map written: ${(d.length / 1024).toFixed(0)} kB of path data`);
